#!/usr/bin/env perl
use strict;
use warnings;
use Cwd qw(getcwd);
use Fcntl qw(O_WRONLY O_CREAT O_EXCL);
use File::Spec;
use FindBin qw($RealBin);

# Run without arguments in the problem directory to generate its Makefile.
# Compilation is a separate step: make or make -j4.
die "Usage: perl $0\nRun without arguments in your problem directory.\n" if @ARGV;
my $problem = getcwd();
die "Cannot resolve the problem directory.\n" unless defined $problem;
die "The current Makefile requires paths without whitespace.\n"
    if $problem =~ /\s/ || $RealBin =~ /\s/;
my $makefile = File::Spec->catfile($RealBin, 'Makefile');
die "Cannot find FLARE's Makefile beside this script: $makefile\n" unless -f $makefile;
my $user_config = File::Spec->catfile($problem, 'user_config.h');
die "Missing problem configuration: $user_config\n"
    . "Create user_config.h in this problem directory; other directories are not used.\n"
    unless -f $user_config;

# Follow GNU Make's filename precedence so setup and a later plain make use
# the same rules. Preserve local targets/settings, including Sod's test targets.
my ($local_makefile) = grep { -e $_ || -l $_ }
    map { File::Spec->catfile($problem, $_) } qw(GNUmakefile makefile Makefile);
die "Problem makefile is not a regular file: $local_makefile\n"
    if defined $local_makefile && !-f $local_makefile;

if (defined $local_makefile) {
    print "Keeping existing $local_makefile\nRun make in $problem to compile.\n";
    exit 0;
}

$local_makefile = File::Spec->catfile($problem, 'Makefile');
# Exclusive creation prevents accidentally replacing a user's file.
sysopen(my $output, $local_makefile, O_WRONLY | O_CREAT | O_EXCL)
    or die "Cannot create $local_makefile: $!\n";
print {$output} <<'MAKEFILE'
# Generated by FLARE build.pl. Add local build settings before the include.
PROBLEM_DIR := $(abspath $(dir $(lastword $(MAKEFILE_LIST))))
# Use only this problem's compile-time configuration.
override USER_CONFIG := $(PROBLEM_DIR)/user_config.h
MAKEFILE
    or die "Cannot write $local_makefile: $!\n";
print {$output} "include $makefile\n"
    or die "Cannot write $local_makefile: $!\n";
close $output or die "Cannot close $local_makefile: $!\n";
print "Created $local_makefile\nRun make in $problem to compile.\n";
